# Writes examples/globe/earth_data.mojo from Natural Earth (public domain, naturalearthdata.com):
#   ne_50m_land (coastline polygons) and ne_50m_populated_places (cities: name, place, population).
# The globe rasterizes the polygons itself at start-up (Mojo, earth.mojo); this only packs them small:
# rings simplified (Douglas-Peucker, 0.02°), each point as two int16 (lon/180, lat/90 × 32767), base64.
#   pixi run python examples/globe/prep.py <folder with the unzipped shapefiles>
import base64, pathlib, struct, sys

src = pathlib.Path(sys.argv[1])
TOL = 0.02  # degrees


def shapes(path):
    """Polygon rings of a .shp file: lists of (lon, lat)."""
    b = path.read_bytes()
    at = 100
    while at < len(b):
        _, words = struct.unpack(">ii", b[at:at + 8])
        rec = b[at + 8:at + 8 + 2 * words]
        at += 8 + 2 * words
        if struct.unpack("<i", rec[:4])[0] != 5:
            continue
        parts, n = struct.unpack("<ii", rec[36:44])
        starts = list(struct.unpack(f"<{parts}i", rec[44:44 + 4 * parts])) + [n]
        pts = struct.unpack(f"<{2 * n}d", rec[44 + 4 * parts:44 + 4 * parts + 16 * n])
        for i in range(parts):
            yield [(pts[2 * j], pts[2 * j + 1]) for j in range(starts[i], starts[i + 1])]


def simplify(ring):
    if len(ring) < 4:
        return ring
    keep = [False] * len(ring)
    keep[0] = keep[-1] = True
    stack = [(0, len(ring) - 1)]
    while stack:
        a, b = stack.pop()
        (x0, y0), (x1, y1) = ring[a], ring[b]
        dx, dy = x1 - x0, y1 - y0
        dd = dx * dx + dy * dy
        best, at = -1.0, -1
        for i in range(a + 1, b):
            x, y = ring[i]
            if dd == 0:
                d = ((x - x0) ** 2 + (y - y0) ** 2) ** 0.5
            else:
                d = abs(dy * x - dx * y + x1 * y0 - y1 * x0) / dd ** 0.5
            if d > best:
                best, at = d, i
        if best > TOL:
            keep[at] = True
            stack += [(a, at), (at, b)]
    return [p for p, k in zip(ring, keep) if k]


def dbf(path):
    b = path.read_bytes()
    n, head, size = struct.unpack("<IHH", b[4:12])
    fields, at = [], 32
    while b[at] != 0x0D:
        name = b[at:at + 11].split(b"\0")[0].decode()
        fields.append((name, b[at + 16]))
        at += 32
    for r in range(n):
        rec, off, row = b[head + r * size:head + (r + 1) * size], 1, {}
        for name, length in fields:
            row[name] = rec[off:off + length].decode("utf-8", "replace").strip()
            off += length
        yield row


land = [simplify(r) for r in shapes(src / "ne_50m_land.shp")]
land = [r for r in land if len(r) >= 4]
words = [len(land)]
for r in land:
    words += [len(r) >> 15, len(r) & 0x7FFF]
    for lon, lat in r:
        words += [round(max(-1, min(1, lon / 180)) * 32767), round(max(-1, min(1, lat / 90)) * 32767)]
blob = base64.b64encode(struct.pack(f"<{len(words)}h", *words)).decode()

places = []
for row in dbf(src / "ne_50m_populated_places.dbf"):
    pop = float(row.get("POP_MAX") or 0)
    if pop >= 150_000:
        name = row["NAME"].replace('"', "").replace("\\", "")
        places.append((name, float(row["LONGITUDE"]), float(row["LATITUDE"]), pop))
places.sort(key=lambda p: -p[3])

out = pathlib.Path(__file__).with_name("earth_data.mojo")
with out.open("w") as f:
    f.write("# Generated by examples/globe/prep.py from Natural Earth 1:50m (public domain): don't edit.\n")
    f.write(f"# {len(land)} land rings, {sum(len(r) for r in land)} points (simplified to {TOL}°); {len(places)} cities of 150,000+.\n\n")
    f.write(f'comptime LAND = "{blob}"\n\n')
    f.write("comptime CITY_NAMES: List[String] = [\n")
    for p in places:
        f.write(f'    "{p[0]}",\n')
    f.write("]\n\n# lon, lat, population (millions), 0\n")
    f.write("comptime CITIES: List[SIMD[DType.float64, 4]] = [\n")
    for p in places:
        f.write(f"    SIMD[DType.float64, 4]({p[1]:.4f}, {p[2]:.4f}, {p[3] / 1e6:.4f}, 0),\n")
    f.write("]\n")
print(out, len(land), "rings", sum(len(r) for r in land), "points", len(blob), "base64 bytes", len(places), "cities")
