"""mojoui/lucide_nodes.mojo from Lucide's own icon data (the version Personal Note ships: its node_modules/lucide), ISC licence.
   pixi run python scripts/gen_lucide_nodes.py [path to lucide/dist/esm/icons]
Each icon becomes one line of elements: `tag k=v k=v…` joined by '|' (a path's d keeps its spaces; values never hold '|' or '=')."""
import re
import sys
from pathlib import Path

ICONS = Path(sys.argv[1] if len(sys.argv) > 1 else Path.home() / "Projects/personalnotev2/node_modules/lucide/dist/esm/icons")
JS = Path.home() / "Projects/personalnotev2/src/icons.js"
EXTRA = ["sun", "pen-line", "sparkles", "layout-grid", "globe", "bookmark", "lock", "link", "image", "plane", "gauge", "file-pen-line",
         "git-fork", "network", "type", "mouse-pointer-2", "corner-down-left", "arrow-up", "arrow-down", "puzzle", "brain", "keyboard",
         "settings", "palette", "pen", "file", "notebook", "house", "shopping-cart", "calendar", "book", "map", "pencil-line", "circle"]


def kebab(name):
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"-\1", re.sub(r"(?<=[A-Za-z])(\d)", r"-\1", name)).lower()


names = set(EXTRA)
for m in re.finditer(r"\b([A-Z][A-Za-z0-9]+)\b", JS.read_text().split("export const icons")[0]):
    if m.group(1) not in ("import", "createIcons"):
        names.add(kebab(m.group(1)))
out, have = [], []
for n in sorted(names):
    f = ICONS / f"{n}.mjs"
    if not f.exists():
        continue
    src = f.read_text()
    els = []
    for tag, attrs in re.findall(r"\[\s*\"(\w+)\",\s*\{([^}]*)\}\s*\]", src, re.S):
        kv = re.findall(r'(\w+):\s*"([^"]*)"', attrs)
        els.append(tag + " " + " ".join(f"{k}={v}" for k, v in kv if k != "key"))
    out.append((n, "|".join(els)))
    have.append(n)
lines = ["# Generated by scripts/gen_lucide_nodes.py from Lucide " + (re.search(r"lucide v([\d.]+)", src) or [0, "?"])[1] +
         " (ISC licence), the icons Personal Note draws. Don't edit.", "# An icon: elements joined by '|', each `tag k=v k=v…` (24×24 box, stroke 2, round caps).", "",
         "def lucide_node(name: String) -> String:"]
for n, body in out:
    lines.append(f'    if name == "{n}":')
    lines.append(f'        return "{body}"')
lines.append('    return ""')
Path(__file__).resolve().parent.parent.joinpath("mojoui/lucide_nodes.mojo").write_text("\n".join(lines) + "\n")
print(f"{len(out)} icons")
