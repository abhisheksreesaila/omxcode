"""Writes mojoui/pow5.mojo: the 128-bit truncated mantissas of 5^q for q = -342 … 308, as Lemire's fast_float
script/table_generation.py makes them (mojoui.json's Eisel–Lemire reader, D-7945). Run: pixi run python scripts/pow5_table.py"""
from pathlib import Path

rows = []
for q in range(-342, 0):
    power5 = 5 ** -q
    z = 0
    while (1 << z) < power5:
        z += 1
    if q >= -27:
        c = 2 ** (z + 127) // power5 + 1
    else:
        c = 2 ** (2 * z + 2 * 64) // power5 + 1
        while c >= (1 << 128):
            c //= 2
    rows.append(c)
for q in range(0, 309):
    power5 = 5 ** q
    while power5 < (1 << 127):
        power5 *= 2
    while power5 >= (1 << 128):
        power5 //= 2
    rows.append(power5)
lines = ["# mojoui.pow5: the 128-bit truncated mantissas of 5^q, q = -342 … 308 (Lemire's fast_float table; generated by",
         "# scripts/pow5_table.py: two 64-bit words each, high first). mojoui.json's Eisel–Lemire reader multiplies by them.",
         "", "comptime POW5_MIN = -342", f"comptime POW5_COUNT = {len(rows)}",
         "comptime POW5: List[UInt64] = ["]
lines += [f"    0x{c >> 64:016X}, 0x{c & ((1 << 64) - 1):016X}," for c in rows]
lines.append("]")
Path(__file__).resolve().parent.parent.joinpath("mojoui/pow5.mojo").write_text("\n".join(lines) + "\n")
