"""docs/llms-full.txt: the docs an agent needs, in one plain-text file (the llmstxt.org convention).

  pixi run python scripts/llms.py          # rewrite docs/llms-full.txt
  pixi run python scripts/llms.py --check  # exit 1 if docs/llms-full.txt is out of date

docs/llms.txt is the hand-written index; this file is the same docs, concatenated, so an agent reads them in one fetch.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "llms-full.txt"
# The order an agent should read them in: the story, the API, the design, the agent host, the matrix.
SOURCES = ["README.md", "docs/reference.md", "docs/architecture.md", "docs/agent.md", "docs/ui-threads.md", "docs/components.md"]


def build() -> str:
    parts = ["# omxcode: the docs in one file\n\n"
             "Generated by `scripts/llms.py` from the files below (don't edit by hand). "
             "The index is https://abhisheksreesaila.github.io/omxcode/llms.txt\n"
             "Relative links are relative to the repository root: https://github.com/abhisheksreesaila/omxcode/blob/main/\n"]
    for src in SOURCES:
        parts.append(f"\n\n---\n\n<!-- source: {src} -->\n\n" + (ROOT / src).read_text().strip() + "\n")
    return "".join(parts)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/llms-full.txt is stale: run pixi run python scripts/llms.py")
            sys.exit(1)
        print("docs/llms-full.txt is current")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)} ({len(text):,} chars)")
