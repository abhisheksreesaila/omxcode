"""Writes mojoui/icons_data.mojo from the Lucide SVGs in mojoui/hosts/static/icons/ (the web host's icons),
so the GTK host draws the same icons. Run after adding an icon: pixi run python scripts/gen_icons.py"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LUCIDE = ["table", "pivot", "chart-bar", "note", "undo", "save", "open", "close", "sort", "filter-off", "row-plus", "row-minus",
          "view", "zoom", "category", "formula", "comment", "shape", "text", "organise", "format", "share", "import", "database", "sample", "grid", "sheet", "file", "export", "upload", "chevron",
          "bold", "italic", "underline", "strikethrough", "text-colour", "fill", "align-left", "align-center", "align-right", "currency", "percent", "decimals-less", "decimals-more", "clear-format", "rename", "settings", "chevron-right", "back", "copy"]

out = ['# Generated by scripts/gen_icons.py from mojoui/hosts/static/icons/*.svg (Lucide, ISC licence). Don\'t edit.',
       '# The SVGs the GTK host writes to its icon folder (stroke colour filled in per variant).', '',
       'comptime LUCIDE_NAMES: List[String] = [' + ", ".join(f'"{n}"' for n in LUCIDE) + ']', '', '',
       'def lucide_svg(name: String) -> String:', '    """The icon\'s SVG with `currentColor` in place of a colour ("" if unknown)."""']
for n in LUCIDE:
    svg = (ROOT / "mojoui/hosts/static/icons" / f"{n}.svg").read_text().split("-->", 1)[-1].strip()
    svg = re.sub(r"\s+", " ", svg).replace('"', "'")
    out.append(f'    if name == "{n}":')
    out.append(f'        return "{svg}"')
out.append('    return ""')
(ROOT / "mojoui/icons_data.mojo").write_text("\n".join(out) + "\n")
print("wrote", len(LUCIDE), "icons")
